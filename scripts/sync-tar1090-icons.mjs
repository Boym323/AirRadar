import { mkdir, rm, writeFile } from "node:fs/promises";
import { join } from "node:path";
import vm from "node:vm";

const TAR1090_COMMIT = "115e40e6968eb6cdeb9e5ed7bdcdd1a2234ed2a2";
const TAR1090_REPOSITORY = "https://github.com/wiedehopf/tar1090";
const MARKERS_URL = `${TAR1090_REPOSITORY}/raw/${TAR1090_COMMIT}/html/markers.js`;
const LICENSE_URL = `${TAR1090_REPOSITORY}/raw/${TAR1090_COMMIT}/LICENSE`;
const outputDirectory = new URL("../public/aircraft-icons-tar1090/", import.meta.url);
const sourceMapPath = new URL("../lib/aircraft/tar1090-icon-map.ts", import.meta.url);

function requireMatch(value, pattern, label) {
  const match = value.match(pattern);
  if (!match) throw new Error(`Unable to parse tar1090 ${label}`);
  return match;
}

function extractObject(source, declaration, endMarker) {
  const start = source.indexOf(declaration);
  if (start < 0) throw new Error(`Unable to find tar1090 ${declaration}`);
  const end = source.indexOf(endMarker, start);
  if (end < 0) throw new Error(`Unable to find end of tar1090 ${declaration}`);
  return source.slice(start, end);
}

function readTar1090Objects(source) {
  const context = {};
  const shapesSource = `${extractObject(source, "let shapes = {", "\n{\n    let kv = Object.entries(shapes);")}\nglobalThis.__aircraftShapes = shapes;`;
  vm.runInNewContext(shapesSource, context, { timeout: 5_000 });

  const typeMapSource = `const _ulac = ["cessna", 0.92];\n${extractObject(source, "let TypeDesignatorIcons = {", "\nlet TypeDescriptionIcons")}\nglobalThis.__typeDesignatorIcons = TypeDesignatorIcons;`;
  vm.runInNewContext(typeMapSource, context, { timeout: 5_000 });

  return {
    shapes: context.__aircraftShapes,
    typeDesignatorIcons: context.__typeDesignatorIcons,
  };
}

function escapeXml(value) {
  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll('"', "&quot;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;");
}

function renderShape(shape, scale) {
  const width = Number(shape.w) * scale;
  const height = Number(shape.h) * scale;
  const strokeWidth = 0.75 * (shape.strokeScale ?? 1);

  if (shape.svg) {
    return shape.svg
      .replaceAll("fillColor", "#ffffff")
      .replaceAll("strokeColor", "#ffffff")
      .replaceAll("strokeWidth", String(strokeWidth))
      .replace("SIZE", `width="${width}" height="${height}"`);
  }

  const paths = Array.isArray(shape.path) ? shape.path : [shape.path];
  const body = paths.filter(Boolean).map((path) => (
    `<path paint-order="stroke" fill="#ffffff" stroke="#ffffff" stroke-width="${2 * strokeWidth}" d="${escapeXml(path)}"/>`
  )).join("");
  const accents = shape.accent
    ? (Array.isArray(shape.accent) ? shape.accent : [shape.accent])
      .map((path) => `<path fill="none" stroke="#ffffff" stroke-width="${0.6 * (shape.accentMult ?? 1) * strokeWidth}" d="${escapeXml(path)}"/>`)
      .join("")
    : "";
  const aspect = shape.noAspect ? " preserveAspectRatio=\"none\"" : "";
  const transform = shape.transform ? ` transform="${escapeXml(shape.transform)}"` : "";

  return [
    `<?xml version="1.0" encoding="UTF-8"?>`,
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${escapeXml(shape.viewBox)}" width="${width}" height="${height}"${aspect}>`,
    `<g${transform}>${body}${accents}</g>`,
    `</svg>`,
  ].join("");
}

async function fetchText(url) {
  const response = await fetch(url, { headers: { "User-Agent": "AirRadar tar1090 icon sync" } });
  if (!response.ok) throw new Error(`Failed to download ${url}: ${response.status} ${response.statusText}`);
  return response.text();
}

const [markersSource, license] = await Promise.all([
  fetchText(MARKERS_URL),
  fetchText(LICENSE_URL),
]);
const { shapes, typeDesignatorIcons } = readTar1090Objects(markersSource);

await rm(outputDirectory, { recursive: true, force: true });
await mkdir(outputDirectory, { recursive: true });
await mkdir(new URL("../lib/aircraft/", import.meta.url), { recursive: true });

const iconCodes = [];
for (const [rawCode, iconDefinition] of Object.entries(typeDesignatorIcons)) {
  const code = rawCode.toUpperCase();
  if (!/^[A-Z0-9]{3,4}$/.test(code)) continue;

  const [shapeName, scale] = iconDefinition;
  const shape = shapes[shapeName];
  if (!shape) {
    console.warn(`Skipping ${code}: tar1090 shape ${shapeName} is missing`);
    continue;
  }

  await writeFile(new URL(`${code}.svg`, outputDirectory), `${renderShape(shape, Number(scale) || 1)}\n`, "utf8");
  iconCodes.push(code);
}

iconCodes.sort();
await writeFile(
  sourceMapPath,
  [
    "// Generated by scripts/sync-tar1090-icons.mjs; do not edit by hand.",
    `// Source: ${MARKERS_URL}`,
    `export const TAR1090_ICON_CODES = new Set(${JSON.stringify(iconCodes)});`,
    "",
  ].join("\n"),
  "utf8",
);

await writeFile(new URL("LICENSE", outputDirectory), license, "utf8");
await writeFile(
  new URL("README.md", outputDirectory),
  [
    "# tar1090 aircraft icons",
    "",
    `These SVG assets are generated from [wiedehopf/tar1090](${TAR1090_REPOSITORY}) at commit \`${TAR1090_COMMIT}\`.`,
    "The original tar1090 marker definitions are converted from inline shape data to one local SVG per ICAO type-designator.",
    "",
    "The upstream project is licensed under GPL-2.0-or-later; the corresponding upstream license is included in this directory.",
    "The generated SVG files are modified representations of the upstream marker definitions.",
    "",
    `Source marker definitions: ${MARKERS_URL}`,
    "",
  ].join("\n"),
  "utf8",
);

console.log(`Generated ${iconCodes.length} tar1090 aircraft icons from ${TAR1090_COMMIT}.`);
